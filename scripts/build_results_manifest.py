"""Build results/manifest.json: one entry per result file, so every published number can be traced.

For each ``results/**/*.jsonl`` it records the SHA-256, record count, model and provider, the case
set (golden, or generated with seed and per-track count), prompt version, run settings and the
content hashes of the questions answered. Settings come from the run's ``<file>.meta.json`` when the
run script wrote one, otherwise from ``results/legacy_metadata.json`` (hand-recorded, older runs).

    uv run python scripts/build_results_manifest.py          # writes results/manifest.json
    uv run python scripts/build_results_manifest.py --check  # fails if the manifest is stale
"""

from __future__ import annotations

import argparse
import fnmatch
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

from lilavati.bench.datasets import BenchmarkTestCase, case_content_hash, load_all_test_cases
from lilavati.bench.generator import generate_cases
from lilavati.bench.llm_eval import case_index

RESULTS = Path("results")


def cases_for(entry: dict[str, Any]) -> list[BenchmarkTestCase]:
    if entry["case_set"] == "golden":
        return load_all_test_cases()
    return generate_cases(int(entry["seed"]), int(entry["per_track"]))


def legacy_settings(rel: str, table: dict[str, Any]) -> dict[str, Any] | None:
    for pattern, settings in table.items():
        if not pattern.startswith("_") and fnmatch.fnmatch(rel, pattern):
            return dict(settings)
    return None


def build() -> dict[str, Any]:
    table = json.loads((RESULTS / "legacy_metadata.json").read_text())
    files = []
    for path in sorted(RESULTS.rglob("*.jsonl")):
        rel = path.relative_to(RESULTS).as_posix()
        rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
        meta_path = path.with_suffix(".meta.json")
        if meta_path.exists():
            settings = json.loads(meta_path.read_text())
            settings.setdefault("status", "current")
            source = meta_path.name
        else:
            found = legacy_settings(rel, table)
            if found is None:
                raise SystemExit(f"{rel}: no .meta.json and no entry in legacy_metadata.json")
            settings, source = found, "legacy_metadata.json"
        if settings.get("case_set") in ("filings", "extraction"):  # real filings: no benchmark case set
            files.append({
                "path": f"results/{rel}", "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                "n_records": len(rows), "model": rows[0]["model"],
                **{k: v for k, v in settings.items() if k != "model"},
                "metadata_source": source, "case_hashes": [],
            })
            continue
        index = case_index(cases_for(settings))
        missing = sorted({r["case"] for r in rows} - set(index))
        if missing:
            raise SystemExit(f"{rel}: cases {missing[:3]} not in the declared case set")
        for r in rows:
            if "case_hash" in r and r["case_hash"] != case_content_hash(index[r["case"]]):
                raise SystemExit(f"{rel}: case {r['case']} hash does not match the declared case set")
        files.append({
            "path": f"results/{rel}",
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "n_records": len(rows),
            "provider": rows[0].get("provider", settings.get("provider")),
            "model": rows[0]["model"],
            **{k: v for k, v in settings.items() if k not in ("provider", "model")},
            "metadata_source": source,
            "case_hashes": sorted({case_content_hash(index[r["case"]]) for r in rows}),
        })
    return {"about": "Generated by scripts/build_results_manifest.py; do not edit by hand.",
            "files": files}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if results/manifest.json is stale")
    args = ap.parse_args()
    manifest = build()
    text = json.dumps(manifest, indent=2) + "\n"
    target = RESULTS / "manifest.json"
    if args.check:
        if not target.exists() or target.read_text() != text:
            sys.exit("results/manifest.json is stale: run scripts/build_results_manifest.py")
        print("manifest up to date")
        return
    target.write_text(text)
    print(f"wrote {target} ({len(manifest['files'])} files)")


if __name__ == "__main__":
    main()
