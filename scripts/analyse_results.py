"""Analyse every result file listed in results/manifest.json; write results/ANALYSIS.md and analysis.json.

No API calls: everything is computed from stored replies. Rebuild the manifest first if result
files changed (scripts/build_results_manifest.py).

    uv run python scripts/analyse_results.py          # writes the two files
    uv run python scripts/analyse_results.py --check  # fails if either is stale
"""

from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path
from typing import Any

from lilavati.bench.analysis import load_records, paired_difference, summarise
from lilavati.bench.datasets import load_all_test_cases
from lilavati.bench.generator import generate_cases

RESULTS = Path("results")


def _cases(entry: dict[str, Any]) -> list[Any]:
    if entry["case_set"] == "golden":
        return load_all_test_cases()
    return generate_cases(int(entry["seed"]), int(entry["per_track"]))


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def _outcomes(o: dict[str, int]) -> str:
    return ", ".join(f"{k} {v}" for k, v in o.items() if v and k != "answered") or "none"


def main() -> None:
    manifest = json.loads((RESULTS / "manifest.json").read_text())
    rows: list[dict[str, Any]] = []
    for entry in manifest["files"]:
        if entry.get("case_set") in ("filings", "extraction"):
            # real-filing runs: summarised in results/filings/ (Tutorial 08) and by
            # scripts/run_extraction_repair_eval.py --report (docs/agent-workflows.md)
            continue
        s = summarise(load_records(entry["path"]), _cases(entry))
        rows.append({"entry": entry, "summary": s})

    lines = ["# Results analysis", "",
             "Generated by `scripts/analyse_results.py` from the files in `results/manifest.json`; do not edit.",
             "Item mean = mean per-case score (fraction of answer fields correct), with every non-answer",
             "scored 0. 95% CI = percentile bootstrap over items (5,000 resamples, seed 0). Accuracy on",
             "answered = mean score over items with a parsed answer. Tool grounding = share of numeric",
             "answer fields equal to a number returned by a tool (tool runs only).", "",
             "## Current results", "",
             "| File | Model | Arm | Cases | Prompt | Answered | Not answered | Accuracy on answered | Item mean (95% CI) | Tool grounding |",
             "| :--- | :--- | :--- | :--- | :---: | ---: | :--- | ---: | :--- | ---: |"]
    for r in rows:
        e, s = r["entry"], r["summary"]
        if e["status"] != "current":
            continue
        cases = "golden 7" if e["case_set"] == "golden" else f"generated s{e['seed']}×{e['per_track']}/track"
        if s["samples"] > 1:
            cases += f", {s['samples']} passes"
        lo, hi = s["item_mean_ci95"]
        lines.append(
            f"| `{Path(e['path']).name}` | {e['model']} | {e.get('arm', 'no_tools')} | {cases} | "
            f"{e['prompt_version']} | {s['outcomes']['answered']}/{s['n']} | {_outcomes(s['outcomes'])} | "
            f"{_pct(s['accuracy_on_answered'])} | {s['item_mean']:.3f} ({lo:.2f}–{hi:.2f}) | "
            f"{_pct(s['tool_grounding'])} |")

    # Paired comparisons: same model, same questions, no tools vs tools.
    pairs = []
    by_key = {(r["entry"]["model"], r["entry"].get("arm", "no_tools"), r["entry"]["prompt_version"],
               r["entry"]["case_set"]): r for r in rows if r["entry"]["status"] == "current"}
    for (model, arm, pv, cs), r in sorted(by_key.items()):
        if arm != "tools":
            continue
        base = by_key.get((model, "no_tools", pv, cs))
        if base is None:
            continue
        cases = _cases(r["entry"])
        d = paired_difference(load_records(base["entry"]["path"]), load_records(r["entry"]["path"]), cases)
        pairs.append({"model": model, "prompt_version": pv, **d})
    if pairs:
        lines += ["", "## Paired comparison: tools minus no tools (same questions, matched by case hash)", "",
                  "| Model | Pairs | No tools | Tools | Difference (95% CI) | Better / same / worse |",
                  "| :--- | ---: | ---: | ---: | :--- | :--- |"]
        for p in pairs:
            lo, hi = p["diff_ci95"]
            lines.append(f"| {p['model']} | {p['n_pairs']} | {p['mean_a']:.3f} | {p['mean_b']:.3f} | "
                         f"{p['mean_diff']:+.3f} ({lo:+.2f} to {hi:+.2f}) | {p['improved']} / {p['same']} / {p['worse']} |")

    lines += ["", "## Field-level misses on answered items (current files)", "",
              "Relative error = |answer − expected| / |expected| (numbers only).", "",
              "| File | Field | Misses | Median relative error |", "| :--- | :--- | ---: | ---: |"]
    for r in rows:
        if r["entry"]["status"] != "current":
            continue
        for key, ms in sorted(r["summary"]["field_misses"].items()):
            errs = [m["rel_err"] for m in ms if m["rel_err"] is not None]
            med = f"{statistics.median(errs):.3g}" if errs else "n/a (boolean or missing)"
            lines.append(f"| `{Path(r['entry']['path']).name}` | {key} | {len(ms)} | {med} |")

    lines += ["", "## Superseded files (kept for transparency; do not cite)", ""]
    for r in rows:
        e = r["entry"]
        if e["status"] != "current":
            lines.append(f"- `{e['path']}`: {e['status']}, prompt {e['prompt_version']}. {e.get('notes', '')}".rstrip())
    md = "\n".join(lines) + "\n"
    out = [{"path": r["entry"]["path"], "status": r["entry"]["status"],
            **{k: v for k, v in r["summary"].items() if k != "field_misses"},
            "field_misses": {k: len(v) for k, v in r["summary"]["field_misses"].items()}} for r in rows]
    js = json.dumps({"files": out, "paired": pairs}, indent=2, default=str) + "\n"
    if "--check" in sys.argv[1:]:
        stale = [name for name, text in (("ANALYSIS.md", md), ("analysis.json", js))
                 if (RESULTS / name).read_text() != text]
        if stale:
            raise SystemExit(f"stale: {', '.join(stale)}; run scripts/analyse_results.py")
        print("results/ANALYSIS.md and results/analysis.json are up to date")
        return
    (RESULTS / "ANALYSIS.md").write_text(md)
    (RESULTS / "analysis.json").write_text(js)
    print(f"wrote results/ANALYSIS.md and results/analysis.json ({len(rows)} files, {len(pairs)} paired comparisons)")


if __name__ == "__main__":
    main()
